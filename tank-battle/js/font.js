// 3x5 pixel font. Each glyph is five rows of three bits.
const G = {
  '0': '111101101101111', '1': '010110010010111', '2': '111001111100111', '3': '111001111001111',
  '4': '101101111001001', '5': '111100111001111', '6': '111100111101111', '7': '111001010010010',
  '8': '111101111101111', '9': '111101111001111',
  A: '010101111101101', B: '110101110101110', C: '011100100100011', D: '110101101101110',
  E: '111100110100111', F: '111100110100100', G: '011100101101011', H: '101101111101101',
  I: '111010010010111', J: '001001001101010', K: '101101110101101', L: '100100100100111',
  M: '101111111101101', N: '110101101101101', O: '010101101101010', P: '110101110100100',
  Q: '010101101110011', R: '110101110101101', S: '011100010001110', T: '111010010010010',
  U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101',
  Y: '101101010010010', Z: '111001010100111',
  '-': '000000111000000', '.': '000000000000010', ':': '000010000010000', 'x': '000101010101000',
  '!': '010010010000010', '/': '001001010100100', '>': '100010001010100', ' ': '000000000000000',
};

/** Draw text with the pixel font. align: 'left' | 'center' | 'right'. Returns width in px. */
export function text(g, str, x, y, color = '#fff', scale = 1, align = 'left') {
  str = String(str).toUpperCase();
  const w = (str.length * 4 - 1) * scale;
  if (align === 'center') x -= Math.floor(w / 2);
  else if (align === 'right') x -= w;
  g.fillStyle = color;
  for (let i = 0; i < str.length; i++) {
    const bits = G[str[i]] || G[' '];
    for (let r = 0; r < 5; r++) for (let c = 0; c < 3; c++) {
      if (bits[r * 3 + c] === '1') g.fillRect(x + (i * 4 + c) * scale, y + r * scale, scale, scale);
    }
  }
  return w;
}
